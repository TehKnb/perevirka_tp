/** Як увімкнути доступ вручну в кожному браузері. */
function permissionSteps(browser: BrowserId, kind: DeviceKind): string[] {
  const w = PERMISSION_WORDS[kind];
  switch (browser) {
    case 'chrome':
      return [
        'Натисніть на значок ліворуч від адреси сайту (два повзунки або замок).',
        `Увімкніть перемикачі ${w.toggles}.`,
      ];
    case 'edge':
      return [
        'Натисніть на значок замка ліворуч від адреси сайту.',
        `У розділі «Дозволи для цього сайту» для ${w.toggles} оберіть «Дозволити».`,
      ];
    case 'opera':
      return [
        'Натисніть на значок замка ліворуч від адреси сайту.',
        `Для ${w.toggles} оберіть «Дозволити».`,
      ];
    case 'firefox':
      return [
        'Натисніть на перекреслений значок камери чи мікрофона ліворуч від адреси сайту.',
        'Поруч із «Заблоковано» натисніть хрестик, щоб зняти заборону.',
        `Натисніть «Спробувати ще раз» і дозвольте доступ до ${w.of}.`,
      ];
    case 'safari':
      return [
        'Оновіть сторінку (⌘R) — Safari запитає дозвіл знову. Оберіть «Дозволити».',
        `Якщо не запитує: у меню Safari відкрийте «Налаштування для цього вебсайту» (Settings for This Website) і для ${w.toggles} оберіть «Дозволити».`,
      ];
    default:
      return [`Натисніть на значок замка або камери біля адреси сайту й дозвольте доступ до ${w.of}.`];
  }
}

export interface PermissionHelp {
  title: string;
  body: string;
  /** Підпис над кроками (порожній — без підпису). */
  stepsLead: string;
  steps: string[];
  footer: string;
}

/**
 * Пояснення, коли браузер не дав доступу: чи покаже «Спробувати ще раз» вікно знову,
 * чи доступ треба вмикати вручну — і де саме в цьому браузері.
 * autoContinue — сторінка сама продовжить, щойно дозвіл з'явиться (браузер повідомляє про зміни).
 */
export function permissionHelp(mode: DenialMode, kind: DeviceKind, browser: BrowserId, autoContinue: boolean): PermissionHelp {
  const w = PERMISSION_WORDS[kind];
  const steps = permissionSteps(browser, kind);
  const footer = autoContinue
    ? 'Щойно доступ буде дозволено, сторінка продовжить сама.'
    : browser === 'firefox' || browser === 'safari'
      ? ''
      : 'Потім натисніть «Спробувати ще раз».';
  if (mode === 'blocked') {
    return {
      title: ERROR_TITLES.denied[kind],
      body: `Браузер запам’ятав заборону й більше не показує вікно із запитом. Дозвольте доступ до ${w.of} вручну:`,
      stepsLead: '',
      steps,
      footer,
    };
  }
  if (mode === 'dismissed') {
    return {
      title: `Ви не надали доступ до ${w.of}`,
      body: 'Натисніть «Спробувати ще раз» — браузер знову покаже вікно із запитом. У ньому оберіть «Дозволити».',
      stepsLead: 'Якщо вікно не з’являється:',
      steps,
      footer,
    };
  }
  return {
    title: ERROR_TITLES.denied[kind],
    body: 'Натисніть «Спробувати ще раз» і у вікні браузера оберіть «Дозволити».',
    stepsLead: 'Якщо вікно із запитом не з’являється, увімкніть доступ вручну:',
    steps,
    footer,
  };
}
