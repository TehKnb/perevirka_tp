/** Числа й булеві значення розширюємо до number/boolean, щоб функції приймали будь-які пороги (наприклад, у тестах). */
type Widen<T> = T extends number
  ? number
  : T extends boolean
    ? boolean
    : T extends string
      ? T
      : { [K in keyof T]: Widen<T[K]> };

export type AppConfig = Widen<typeof config>;
